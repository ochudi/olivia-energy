/**
 * Builds the files that are pasted into a hosted Supabase project's SQL
 * Editor:
 *
 *   supabase/hosted-setup.sql   a new project: the migrations plus the
 *                               content seeds (settings, publications,
 *                               commentary, starter articles) in a single
 *                               transaction, so it either applies completely
 *                               or changes nothing. Refuses to run twice.
 *   supabase/hosted-updates/2026-10-03-commentary-and-formats.sql
 *                               a project that already ran hosted-setup.sql:
 *                               just that one migration and the commentary
 *                               seed. Additive, and safe to run twice.
 *   supabase/hosted-updates/2026-11-05-location-and-nipex.sql
 *                               a project seeded before 5 November 2026:
 *                               three settings rows brought into line with
 *                               the client's instructions (the Nigerian
 *                               location, the NIPEX line). Safe to run twice.
 *
 *   npm run db:hosted-sql            # rewrite the files
 *   npm run db:hosted-sql -- --check # exit 1 if any is out of date
 *
 * Why a pasted file rather than `supabase db push`: the project may be
 * shared with other applications, whose migration history `db push` would
 * trip over. Everything here lives in the olivia_energy schema and touches
 * nothing else. supabase/seeds/local-admin.sql is left out on purpose (its
 * password is public); create the first admin with scripts/create-admin.mjs.
 */
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const supabase = path.join(root, "supabase");
const out = path.join(supabase, "hosted-setup.sql");

const migrations = fs
  .readdirSync(path.join(supabase, "migrations"))
  .filter((name) => name.endsWith(".sql"))
  .sort()
  .map((name) => `migrations/${name}`);
const parts = [
  ...migrations,
  "seed.sql",
  "seeds/publications.sql",
  "seeds/commentary.sql",
  "seeds/starter-articles.sql",
];

const header = `-- =====================================================================
-- OLIVIA ENERGY — hosted setup. GENERATED by scripts/hosted-sql.mjs from
-- supabase/migrations and the content seeds; edit those and re-run
-- \`npm run db:hosted-sql\`, not this file.
--
-- Use: Supabase dashboard → SQL Editor → New query → paste this whole file
-- → Run. Then Project Settings → Data API → Exposed schemas → add
-- olivia_energy. The last statement prints the row counts.
--
-- Safe on a project shared with other applications: it creates the
-- olivia_energy schema, the olivia-energy-media storage bucket and four
-- policies on storage.objects that apply to that bucket only. It creates,
-- alters, revokes or drops nothing else, and it runs in one transaction:
-- if any statement fails, or the schema already exists, nothing changes.
-- =====================================================================

begin;

do $$
begin
  if exists (select 1 from pg_namespace where nspname = 'olivia_energy') then
    raise exception 'The olivia_energy schema already exists, so this script has already been run. Nothing was changed.';
  end if;
end
$$;
`;

const footer = `
-- Tell the Data API about the new schema's tables.
notify pgrst, 'reload schema';

commit;

select
  (select count(*) from olivia_energy.settings) as settings,
  (select count(*) from olivia_energy.publications where kind = 'journal') as journal_articles,
  (select count(*) from olivia_energy.publications where kind = 'op-ed') as op_eds,
  (select count(*) from olivia_energy.publications where kind = 'mention') as mentions,
  (select count(*) from olivia_energy.posts) as articles,
  (select count(*) from storage.buckets where id = 'olivia-energy-media') as media_bucket;
`;

/** The guard every update opens with: the schema must already exist. */
const requireSchema = `
begin;

do $$
begin
  if not exists (select 1 from pg_namespace where nspname = 'olivia_energy') then
    raise exception 'The olivia_energy schema does not exist yet. Run supabase/hosted-setup.sql first. Nothing was changed.';
  end if;
end
$$;
`;

/**
 * The updates, oldest first. Each is pasted once into a project that already
 * ran hosted-setup.sql at an earlier state; each is safe to run twice.
 */
const updates = [
  {
    name: "2026-10-03-commentary-and-formats.sql",
    parts: [
      "migrations/20261003120000_commentary_and_formats.sql",
      "seeds/commentary.sql",
    ],
    header: `-- =====================================================================
-- OLIVIA ENERGY — hosted update, 3 October 2026: commentary and formats.
-- GENERATED by scripts/hosted-sql.mjs from
-- supabase/migrations/20261003120000_commentary_and_formats.sql and
-- supabase/seeds/commentary.sql; edit those and re-run
-- \`npm run db:hosted-sql\`, not this file.
--
-- What it does, on a project that already ran hosted-setup.sql:
--   1. adds columns to olivia_energy.publications (kind, published_on,
--      topics, pull_quote, syndication) and olivia_energy.posts (format),
--      with two check constraints and one index;
--   2. adds the founder's 11 BusinessDay op-eds and 13 BusinessDay mentions
--      (the 9 journal articles already there become kind 'journal').
--
-- Use: Supabase dashboard → SQL Editor → New query → paste this whole file
-- → Run. The last statement prints the rows per kind; expect journal 9,
-- mention 13, op-ed 11.
--
-- Safe on a project shared with other applications: it touches only the
-- olivia_energy schema. Nothing is dropped, renamed or relaxed; existing
-- rows keep every value. Safe to run twice: every statement is
-- if-not-exists or guarded, and a seed row is added only when no
-- publication already has its URL. Runs in one transaction.
-- =====================================================================
${requireSchema}`,
    footer: `
commit;

select kind, count(*) from olivia_energy.publications group by kind order by kind;
`,
  },
  {
    name: "2026-11-05-location-and-nipex.sql",
    parts: ["seeds/updates/2026-11-05-location-and-nipex.sql"],
    header: `-- =====================================================================
-- OLIVIA ENERGY — hosted update, 5 November 2026: location and NIPEX.
-- GENERATED by scripts/hosted-sql.mjs from
-- supabase/seeds/updates/2026-11-05-location-and-nipex.sql; edit that and
-- re-run \`npm run db:hosted-sql\`, not this file.
--
-- What it does, on a project that ran hosted-setup.sql before 5 November
-- 2026 (the client's instructions of 3 October 2026): in
-- olivia_energy.settings,
--   1. the Nigerian office in 'addresses' reads "Southwest Nigeria", with
--      no town or state; the United States office is untouched;
--   2. the retail outlets figure in 'stats' reads "Opened in Southwest
--      Nigeria in 2020"; the other figures are untouched;
--   3. 'nipex_wording' gets the NIPEX vendor ID and categories, only where
--      the line is still empty (an admin's own wording is kept).
-- A project set up with the current hosted-setup.sql already has these
-- values, and this file then changes nothing.
--
-- Use: Supabase dashboard → SQL Editor → New query → paste this whole file
-- → Run. The last statement prints the three rows. Then save Settings once
-- in Admin, or call POST /api/revalidate for "settings", so the site's
-- cached copy refreshes.
--
-- Safe on a project shared with other applications: it touches only three
-- rows of olivia_energy.settings. Nothing is created, dropped or altered.
-- Safe to run twice: each statement changes a row only when it still
-- needs the change. Runs in one transaction.
-- =====================================================================
${requireSchema}`,
    footer: `
commit;

select key, value
from olivia_energy.settings
where key in ('addresses', 'stats', 'nipex_wording')
order by key;
`,
  },
];

const concat = (names) =>
  names
    .map((name) => {
      const sql = fs.readFileSync(path.join(supabase, name), "utf8").trimEnd();
      return `\n-- >>>>> supabase/${name}\n\n${sql}\n`;
    })
    .join("");

const files = [
  {
    file: out,
    label: "supabase/hosted-setup.sql",
    sql: header + concat(parts) + footer,
  },
  ...updates.map((update) => ({
    file: path.join(supabase, "hosted-updates", update.name),
    label: `supabase/hosted-updates/${update.name}`,
    sql: update.header + concat(update.parts) + update.footer,
  })),
];

if (process.argv.includes("--check")) {
  const stale = files
    .filter(
      ({ file, sql }) =>
        !fs.existsSync(file) || fs.readFileSync(file, "utf8") !== sql,
    )
    .map(({ label }) => label);
  if (stale.length) {
    console.error(
      `${stale.join(" and ")} out of date. Run \`npm run db:hosted-sql\`.`,
    );
    process.exit(1);
  }
  console.log(
    "supabase/hosted-setup.sql and the hosted updates are up to date.",
  );
} else {
  for (const { file, sql } of files) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, sql);
  }
  console.log(
    `Wrote supabase/hosted-setup.sql (${parts.length} files, ${Math.round(files[0].sql.length / 1024)} KB) and ${updates.length} hosted updates: ${updates.map((u) => u.name).join(", ")}.`,
  );
}
